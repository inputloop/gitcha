// Builds the job directory every backend runs: the source, the harnesses and a
// generated run.sh. Backends differ only in where run.sh executes, so a job
// behaves the same in the development process backend and in a bContain VM.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { unpackFiles, extractTo } from '../../extension/lib/tar.js';

const HARNESS = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'harness');
export const RESPONSE_MARK = '@@GITCHA-RESPONSE@@';
export const CGI_MARK = '@@GITCHA-RESPONSE-CGI@@';
export const STEP_MARK = '@@GITCHA-STEP@@';
export const FAIL_MARK = '@@GITCHA-FAILED@@';
export const BCONTAIN_EXIT = '[bcontain] container exited with code ';

/** POSIX single-quote a value for a shell script. */
export const q = (s) => `'${String(s).replace(/'/g, `'\\''`)}'`;

export function prepare(workdir, job, source) {
  fs.mkdirSync(path.join(workdir, 'src'), { recursive: true });
  fs.mkdirSync(path.join(workdir, 'home'), { recursive: true });
  if (source) extractTo(unpackFiles(source), path.join(workdir, 'src'));
  fs.cpSync(HARNESS, path.join(workdir, 'harness'), { recursive: true });
  const script = job.kind === 'ci' ? ciScript(job.spec.pipeline) : fnScript(workdir, job.spec);
  fs.writeFileSync(path.join(workdir, 'run.sh'), script, { mode: 0o755 });
}

export function ciScript(p) {
  const lines = [
    '#!/bin/sh',
    '# Generated by gitcha-runner for one CI job.',
    'set -u',
    'J=${GITCHA_JOB:-$(cd "$(dirname "$0")" && pwd)}',
    'export HOME="$J/home" CI=true GITCHA=1',
    ...Object.entries(p.env ?? {}).map(([k, v]) => `export ${k}=${q(v)}`),
    'cd "$J/src"',
  ];
  for (const s of p.steps) {
    lines.push(`printf '\\n%s %s\\n' ${q(STEP_MARK)} ${q(s.name)}`);
    lines.push('( set -e', s.run.replace(/\n$/, ''), `) || { rc=$?; printf '\\n%s %s %s\\n' ${q(FAIL_MARK)} ${q(s.name)} "$rc"; exit "$rc"; }`);
  }
  if (p.artifacts) {
    lines.push(
      `[ -d ${q(p.artifacts)} ] || { echo "gitcha: the artifacts directory ${p.artifacts.replace(/[^\w./-]/g, '')} was not produced"; exit 3; }`,
      `tar czf "$J/artifact.tgz" -C ${q(p.artifacts)} .`,
      'if [ -n "${GITCHA_UPLOAD:-}" ]; then wget -q -O /dev/null --post-file="$J/artifact.tgz" "$GITCHA_UPLOAD" || { echo "gitcha: artifact upload failed"; exit 4; }; fi',
    );
  }
  lines.push('exit 0', '');
  return lines.join('\n');
}

export function fnScript(workdir, spec) {
  const { fn, request } = spec;
  fs.writeFileSync(path.join(workdir, 'request.json'), JSON.stringify(request));
  fs.writeFileSync(path.join(workdir, 'body.bin'), Buffer.from(request.body ?? '', 'base64'));
  const head = ['#!/bin/sh', '# Generated by gitcha-runner for one function invocation.', 'set -u',
    'J=${GITCHA_JOB:-$(cd "$(dirname "$0")" && pwd)}', 'export HOME="$J/home"', 'cd "$J/src"'];
  switch (fn.runtime) {
    case 'node':
      return [...head, `exec node "$J/harness/node.mjs" ${q(fn.entry)} "$J/request.json"`, ''].join('\n');
    case 'python':
      return [...head, `exec python3 "$J/harness/python.py" ${q(fn.entry)} "$J/request.json"`, ''].join('\n');
    case 'sh': {
      const h = request.headers ?? {};
      const qs = new URLSearchParams(request.query ?? {}).toString();
      const env = {
        REQUEST_METHOD: request.method, PATH_INFO: request.path, QUERY_STRING: qs, CONTENT_TYPE: h['content-type'] ?? '',
        CONTENT_LENGTH: String(Buffer.from(request.body ?? '', 'base64').length), GATEWAY_INTERFACE: 'CGI/1.1',
      };
      for (const [k, v] of Object.entries(h)) {
        const name = `HTTP_${k.toUpperCase().replace(/[^A-Z0-9]/g, '_')}`;
        if (/^HTTP_[A-Z0-9_]{1,60}$/.test(name)) env[name] = String(v).slice(0, 4096);
      }
      return [...head, ...Object.entries(env).map(([k, v]) => `export ${k}=${q(v)}`),
        `exec sh "$J/harness/cgi.sh" ${q(fn.entry)} "$J/body.bin"`, ''].join('\n');
    }
    case 'orgvm': {
      // Corwin's orgvm jail evaluates one named block; the command is the runner's to configure.
      const [file, block] = fn.entry.split('#');
      return [...head, ': "${GITCHA_ORGVM_CMD:?this runner has no orgvm command configured}"',
        `exec sh -c "$GITCHA_ORGVM_CMD" orgvm ${q(file)} ${q(block)} "$J/request.json"`, ''].join('\n');
    }
    default:
      throw new Error(`unsupported runtime ${fn.runtime}`);
  }
}

/** Parse a CGI response (headers, blank line, body). */
export function parseCgi(buf, exitCode) {
  const text = buf.toString('latin1');
  const m = /^((?:[A-Za-z0-9-]+:[^\r\n]*\r?\n)+)\r?\n/.exec(text);
  if (!m) return { status: exitCode ? 500 : 200, headers: { 'content-type': 'text/plain; charset=utf-8' }, body: buf.toString('base64'), bodyEncoding: 'base64' };
  const headers = {};
  let status = exitCode ? 500 : 200;
  for (const line of m[1].split(/\r?\n/).filter(Boolean)) {
    const i = line.indexOf(':');
    const k = line.slice(0, i).trim().toLowerCase();
    const v = line.slice(i + 1).trim();
    if (k === 'status') status = parseInt(v, 10) || status;
    else headers[k] = v;
  }
  return { status, headers, body: buf.subarray(Buffer.byteLength(m[0], 'latin1')).toString('base64'), bodyEncoding: 'base64' };
}

/** Pull the response and the exit code out of a run's combined output. */
export function readOutput(output, processCode) {
  let response = null;
  let exitCode = processCode;
  const log = [];
  for (const line of output.split('\n')) {
    const clean = line.replace(/\r$/, '');
    if (clean.startsWith(RESPONSE_MARK)) {
      try { response = JSON.parse(Buffer.from(clean.slice(RESPONSE_MARK.length).trim(), 'base64').toString('utf8')); } catch { /* reported below */ }
      continue;
    }
    if (clean.startsWith(CGI_MARK)) {
      const [code, b64 = ''] = clean.slice(CGI_MARK.length).trim().split(' ');
      response = parseCgi(Buffer.from(b64, 'base64'), Number(code));
      continue;
    }
    const bx = clean.indexOf(BCONTAIN_EXIT);
    if (bx !== -1) { exitCode = parseInt(clean.slice(bx + BCONTAIN_EXIT.length), 10); continue; }
    if (clean.startsWith(STEP_MARK)) { log.push(`== ${clean.slice(STEP_MARK.length).trim()} ==`); continue; }
    if (clean.startsWith(FAIL_MARK)) {
      const parts = clean.slice(FAIL_MARK.length).trim().split(' ');
      log.push(`!! step "${parts.slice(0, -1).join(' ')}" failed with exit code ${parts.at(-1)}`);
      continue;
    }
    log.push(clean);
  }
  return { response, exitCode, log: log.join('\n') };
}
